import json, os
from flint import arb, ctx

BITS=int(os.environ.get('ARB_PREC_BITS','160'))
if BITS<160: raise SystemExit('ARB_PREC_BITS must be at least 160')
ctx.prec=BITS

def dot(a,b): return sum(a[i]*b[i] for i in range(3))
def outer(a,b): return tuple(tuple(a[i]*b[j] for j in range(3)) for i in range(3))
def madd(*Ms): return tuple(tuple(sum(M[i][j] for M in Ms) for j in range(3)) for i in range(3))
def mscale(c,M): return tuple(tuple(c*M[i][j] for j in range(3)) for i in range(3))
def contract(A,B): return sum(A[i][j]*B[i][j] for i in range(3) for j in range(3))
def mv(A,v): return tuple(sum(A[i][j]*v[j] for j in range(3)) for i in range(3))
def proj(v,w): return tuple(w[i]-dot(v,w)*v[i] for i in range(3))

def Mg(u,v,g):
    return madd(outer(u,v),outer(v,u),mscale(-g,outer(u,u)),mscale(-g,outer(v,v)))

def tr(M): return sum(M[i][i] for i in range(3))

def sym(M): return all((M[i][j]-M[j][i]).contains(0) for i in range(3) for j in range(3))

# Productive unit triad.
a=(arb('0.8'),arb(0),arb('0.6')); n=(arb(0),arb(0),arb(1)); b=(arb('0.3'),arb('-0.4'),-arb(3).sqrt()/2)
for v in (a,n,b):
    if not dot(v,v).contains(1): raise AssertionError(('unit',v,dot(v,v)))
alpha=dot(a,n); beta=dot(b,n); gamma=dot(a,b)
Ma=Mg(a,n,alpha); Mb=Mg(b,n,beta); Mc=Mg(a,b,gamma)
for M,label in [(Ma,'M_alpha'),(Mb,'M_beta'),(Mc,'M_gamma')]:
    if not sym(M) or not tr(M).contains(0): raise AssertionError(('not STF',label,tr(M)))

rows=[]
for ss in ['1e-24','1','1e24']:
    s=arb(ss)
    S=((s/3,arb('0.2')*s,-arb('0.1')*s),(arb('0.2')*s,-s/2,arb('0.07')*s),(-arb('0.1')*s,arb('0.07')*s,s/6))
    if not tr(S).contains(0): raise AssertionError(('S trace',ss,tr(S)))
    fa=proj(a,mv(S,a)); fn=proj(n,mv(S,n)); fb=proj(b,mv(S,b))
    ad=dot(fa,n)+dot(a,fn); bd=dot(fb,n)+dot(b,fn); gd=dot(fa,b)+dot(a,fb)
    ja=contract(Ma,S); jb=contract(Mb,S); jc=contract(Mc,S)
    for x,y,label in [(ad,ja,'alpha'),(bd,jb,'beta'),(gd,jc,'gamma')]:
        if not (x-y).contains(0): raise AssertionError(('shape tensor current',ss,label,x,y))
    rows.append({'strain_scale':ss,'alpha_dot_direct':str(ad),'alpha_dot_McolonS':str(ja),'beta_dot_direct':str(bd),'beta_dot_McolonS':str(jb),'gamma_dot_direct':str(gd),'gamma_dot_McolonS':str(jc)})

print(json.dumps({
 'arb_precision_bits':BITS,'status':'PASS','cases':len(rows),
 'alpha':str(alpha),'beta':str(beta),'gamma':str(gamma),
 'M_alpha_trace':str(tr(Ma)),'M_beta_trace':str(tr(Mb)),'M_gamma_trace':str(tr(Mc)),
 'interpretation':(
  'Each intrinsic Gram coordinate generates its own symmetric trace-free reset tensor M_g.  For any common symmetric incompressible strain S, the exact common shape current is alpha_dot=M_alpha:S, beta_dot=M_beta:S and gamma_dot=M_gamma:S.  The test tensors are generated by the physical triad itself rather than chosen externally, placing Gram-shape renewal in the same STF transaction space as the Hodge strain tensor.'
 ),'rows':rows
},indent=2,allow_nan=False))
