import json, os
from flint import arb, ctx
BITS=int(os.environ.get('ARB_PREC_BITS','160'))
if BITS<160: raise SystemExit('ARB_PREC_BITS must be at least 160')
ctx.prec=BITS
pi=arb.pi(); rows=[]

def detdiag(l1,l2,l3): return l1*l2*l3
def norm2diag(l1,l2,l3): return l1*l1+l2*l2+l3*l3
def certify_one(x,label,tol='1e-30'):
 t=arb(tol)
 if not x.contains(1) or not (x>1-t and x<1+t): raise AssertionError((label,x))
# Direct sphere-moment formulas for diagonal trace-free S. Orthogonal invariance then gives the tensor invariant law.
for vals in [('2','-1','-1'),('1','0.3','-1.3'),('3','-0.2','-2.8')]:
 l1,l2,l3=map(arb,vals); det=detdiag(l1,l2,l3); S2=norm2diag(l1,l2,l3)
 if not (l1+l2+l3).contains(0): raise AssertionError(('trace',vals))
 d1=l3-l2; d2=l1-l3; d3=l2-l1
 avg_wSw=(l1*d1*d1+l2*d2*d2+l3*d3*d3)/15
 avg_qw2=(d1*d1*(l1/105+(l2+l3)/35)+d2*d2*(l2/105+(l1+l3)/35)+d3*d3*(l3/105+(l1+l2)/35))
 certify_one(avg_wSw/(-arb(3)*det/5),('sphere avg omega S omega',vals))
 certify_one(avg_qw2/(arb(6)*det/35),('sphere avg q omega2',vals))
 for xs in ['1e-6','0.1','0.5','0.9','1']:
  x=arb(xs); shell_rate=(arb(3)/7)*(det/S2)*(13*x*x-7)
  # Reconstruct from carrier f=1-5x^2/3, gL2x2=2x^2/3 and angular moments.
  f=1-arb(5)*x*x/3; gr2=arb(2)*x*x/3
  bracket=f*avg_wSw+gr2*avg_qw2
  avg_w2=S2/5 # exact sphere mean |n cross S n|^2
  direct=bracket/avg_w2
  certify_one(direct/shell_rate,('shell self-stretch rate',vals,xs)) if not shell_rate.contains(0) else None
  rows.append({'eigenvalues':vals,'r_over_L':xs,'det_S':str(det),'S2':str(S2),'shell_stretching_coefficient_P_over_Z':str(shell_rate),'sign_change_factor_13x2_minus7':str(13*x*x-7)})
 global_rate=(arb(4)/3)*det/S2
 rows.append({'eigenvalues':vals,'global_stretching_coefficient_P_over_Z':str(global_rate),'closed_4over3_det_over_S2':str(global_rate)})
print(json.dumps({'arb_precision_bits':BITS,'status':'PASS','cases':len(rows),'interpretation':'For the exact tangent Hodge carrier generated by any STF strain S, orthogonal-invariant sphere moments give the shell stretching coefficient P_shell/Z_shell=(3/7)(det S/|S|^2)(13(r/L)^2-7). The volume-integrated stretching coefficient is int omega.S_u omega / int|omega|^2=(4/3)det S/|S|^2. Thus every positive-gain stationary shape-lock tensor (det S<0) self-amplifies its inner carrier core but de-amplifies the outer collar more strongly, giving negative total self-stretch.','rows':rows},indent=2,allow_nan=False))
