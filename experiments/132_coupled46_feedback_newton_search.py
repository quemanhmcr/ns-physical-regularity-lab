import json, os
from flint import ctx, arb
BITS=int(os.environ.get('ARB_PREC_BITS','160'))
if BITS<160: raise SystemExit('ARB_PREC_BITS must be at least 160')
ctx.prec=BITS
import coupled46_hodge_core as H
import degree6_hodge_servo_core as C
st=H.prepare(); seq=C.solve_degree6_servo()
y=[arb(seq['coeff'][i].mid()) for i in st['t4idx']]
rows=[]
initial=None
for k in range(8):
    fb=H.feedback_map(st,y); F=fb['F']; Ffield=C.combine(F,[st['V6b'][i] for i in st['t4idx']]); fn=C.norm2v(Ffield)
    if initial is None: initial=fn
    J=H.feedback_jacobian(st,y)
    # Certified Jacobian rank at the current point; coordinate rows are only an observer for invertibility.
    jcols=[[J[i][j] for i in range(9)] for j in range(9)]
    jrank=len(C.independent(jcols)[0])
    if jrank!=9: raise AssertionError(('feedback Jacobian rank',k,jrank))
    delta=C.solve(J,[-v for v in F])
    dfield=C.combine(delta,[st['V6b'][i] for i in st['t4idx']])
    rows.append({'iteration':k,'feedback_mismatch_T4_mean_square':str(fn),'Newton_step_T4_mean_square':str(C.norm2v(dfield)),'Jacobian_rank':jrank})
    # Search observer only: re-center after each Newton step to prevent enclosure-width accumulation.
    y=[arb((y[i]+delta[i]).mid()) for i in range(9)]
fb=H.feedback_map(st,y); Ffield=C.combine(fb['F'],[st['V6b'][i] for i in st['t4idx']]); final=C.norm2v(Ffield)
J=H.feedback_jacobian(st,y); jrank=len(C.independent([[J[i][j] for i in range(9)] for j in range(9)])[0])
# Physical candidate fields.  Degree-six output uses the K66 inverse; exact coupled compatibility is measured by F.
V4n=C.norm2v(fb['V4']); V6n=C.norm2v(fb['V6']); Wn=C.norm2v(fb['W'])
# At a fixed point the degree-four residual equals the backreaction generated by phi-y.
B4mis=C.combine(fb['F'],[st['K46'][i] for i in st['t4idx']])
out={
 'arb_precision_bits':BITS,'status':'PASS','iterations':len(rows),'final_feedback_Jacobian_rank':jrank,
 'initial_feedback_mismatch_T4_mean_square':str(initial),'final_feedback_mismatch_T4_mean_square':str(final),
 'candidate_degree4_servo_vorticity_mean_square':str(V4n),'candidate_degree6_servo_vorticity_mean_square':str(V6n),
 'candidate_degree6_lower_silent_W_mean_square':str(Wn),
 'candidate_degree4_coupled_residual_mean_square':str(C.norm2v(B4mis)),
 'candidate_degree6_inverse_residual_mean_square':str(C.norm2v(fb['res6'])),
 'candidate_T4_feedback_coefficients':[str(v) for v in y],
 'rows':rows,
 'interpretation':'This module searches the intrinsic nine-dimensional coupled Hodge feedback law with an analytic directional Jacobian.  The 30 degree-four amplitudes and 49 lower-silent degree-six amplitudes are eliminated exactly by the validated invertible K44 and K66 blocks.  Midpoint recentering is used only to keep the Newton search observer from inheriting interval width from nested ill-conditioned linear solves.  A tiny final residual is a candidate fixed point, not yet an existence theorem; any promotion requires a separate interval/Krawczyk certification around the candidate.'}
print(json.dumps(out,indent=2,allow_nan=False))
