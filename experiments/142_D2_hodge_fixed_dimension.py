import json, os, math
from flint import ctx
BITS=int(os.environ.get('ARB_PREC_BITS','160'))
if BITS<160:raise SystemExit('ARB_PREC_BITS must be at least 160')
ctx.prec=BITS
rows=[]
for l in range(1,14):
 # D2-invariant scalar monomials are all-even for even l and all-odd for odd l.
 if l%2==0:
  m=l//2; inv_poly=math.comb(m+2,2); lower=math.comb(m+1,2) if m>=1 else 0
 else:
  m=(l-1)//2; inv_poly=math.comb(m+1,2) if m>=1 else 0; lower=math.comb(m,2) if m>=2 else 0
 harmonic=inv_poly-lower
 character=((2*l+1)+3*((-1)**l))//4
 if harmonic!=character:raise AssertionError(('D2 harmonic dimension',l,harmonic,character))
 rows.append({'l':l,'D2_invariant_harmonic_dimension':harmonic,'character_formula_dimension':character})
fixed=[]
for d in (4,6,8,10,12):
 m=d//2
 pol=sum((l-1)//2 for l in range(1,d+2,2));tor=sum((l+2)//2 for l in range(4,d+1,2));total=pol+tor;closed=m*m+2*m-2
 if total!=closed:raise AssertionError(('fixed null dimension',d,total,closed))
 fixed.append({'homogeneous_degree_d':d,'D2_fixed_poloidal_null_dimension':pol,'D2_fixed_toroidal_null_dimension':tor,'D2_fixed_total_null_dimension':total,'closed_form_m2_plus_2m_minus_2':closed})
print(json.dumps({'arb_precision_bits':BITS,'status':'PASS','interpretation':'For the proper D2 group generated by pi rotations about the three strain eigenaxes, an invariant scalar monomial has all exponents even when l is even and all exponents odd when l is odd.  Subtracting the invariant r^2 times degree-(l-2) polynomials gives dim Fix_D2(H_l)=(2l+1+3(-1)^l)/4: (l+2)/2 for even l and (l-1)/2 for odd l.  Poloidal and toroidal vector Hodge sectors inherit the same SO(3) irrep dimension.  Therefore the D2-fixed transaction-null space at even degree d=2m has dimension m^2+2m-2.  In particular d=4 gives 6, exactly the old physics-generated Krylov rank, d=6 gives 13, and d=8 gives 22.','harmonic_rows':rows,'fixed_null_rows':fixed},indent=2,allow_nan=False))
